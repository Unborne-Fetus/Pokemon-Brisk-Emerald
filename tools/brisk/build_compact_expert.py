#!/usr/bin/env python3
"""Generate a compact, per-trainer Expert alternate-team plan.

A full fifth gTrainers row overflows a 32MB GBA ROM. Instead, Expert starts
with the separately authored Hard roster and substitutes one explicitly
selected, compatible, already-authored Pokemon from Normal/Kaizo/Easy. The
replacement keeps its own complete moves, ability, item, EVs and nature;
the battle engine applies Expert's levels/IV/EV rules after selection.
This preserves distinct five-mode teams without duplicating thousands of
full TrainerMon structures in ROM.
"""
import argparse
import json
from pathlib import Path
from build_expert_teams import read_sources, pokemon_species, pokemon_level

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "src/data/brisk_expert_patch.h"
SOURCES = ("Normal", "Kaizo", "Easy")


def get_patches():
    trainers = read_sources()
    policy = json.loads((ROOT / "tools/brisk/trainer_fairness_policy.json").read_text())
    exempt = set(policy["protected"]) | set(policy["metadata_only"]) | set(policy["kaizo_bosses"])
    patches = {}
    counts = {"regular": 0, "exempt": 0, "unavailable": 0, "changed": 0}
    for tid, rosters in trainers.items():
        hard = rosters["Hard"][1]
        if tid == "TRAINER_NONE" or tid.endswith("_NONE") or not hard or tid in exempt:
            counts["exempt"] += 1
            continue
        candidates = []
        # Preserve the final signature ace whenever possible. No Pokémon is
        # replaced by a duplicate of one already elsewhere in the party.
        hard_species = [pokemon_species(mon) for mon in hard]
        targets = list(range(len(hard) - 1)) or [0]
        for mode_idx, mode in enumerate(SOURCES):
            other = rosters[mode][1]
            for target in targets:
                for source_idx, mon in enumerate(other):
                    species = pokemon_species(mon)
                    # Do not import an evolved or overleveled source member
                    # into a weaker Expert encounter. Its legal authored level
                    # must not exceed the Hard target it replaces.
                    if pokemon_level(mon) > pokemon_level(hard[target]):
                        continue
                    if species == hard_species[target]:
                        continue
                    if species in (sp for i, sp in enumerate(hard_species) if i != target):
                        continue
                    # Score Normal replacements best: their authored legal
                    # sets are gentler and usually closer to Expert's levels.
                    score = (mode_idx, abs(source_idx - target),
                             abs(target - (len(hard) - 2)),
                             source_idx)
                    candidates.append((score, mode_idx, source_idx, target))
        counts["regular"] += 1
        if not candidates:
            counts["unavailable"] += 1
            continue
        _score, src_mode, source_idx, target_idx = min(candidates)
        # 0 is "no patch". Encode all fields in 16 bits.
        code = 1 + (src_mode << 8) + (source_idx << 4) + target_idx
        patches[tid] = code
        counts["changed"] += 1
    return trainers, patches, counts


def render():
    trainers, patches, counts = get_patches()
    output = [
        "// Generated by tools/brisk/build_compact_expert.py",
        "// One dedicated alternate party patch per eligible trainer.",
        "// 1 + (sourceRow<<8) + (sourceSlot<<4) + targetSlot; 0 = unmodified.",
        "// sourceRow: 0 Normal, 1 Kaizo, 2 Easy",
        "static const u16 sBriskExpertPatch[TRAINERS_COUNT] =",
        "{",
    ]
    for tid, value in patches.items():
        output.append(f"    [{tid}] = {value},")
    output += ["};", ""]
    return "\n".join(output), counts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not args.write and not args.check:
        parser.error("specify --write or --check")
    generated, counts = render()
    if args.write:
        if not OUT.exists() or OUT.read_text() != generated:
            OUT.write_text(generated)
    if args.check and (not OUT.exists() or OUT.read_text() != generated):
        raise SystemExit("Expert patch is missing/stale; use --write")
    if counts["regular"] and not counts["changed"]:
        raise SystemExit("No distinct Expert teams generated")
    print("Expert compact party audit:", counts)
    if counts["unavailable"]:
        print("NOTE: some special/single-member encounters retain unchanged species.")


if __name__ == "__main__":
    main()
